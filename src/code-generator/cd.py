"""PolarPandas v5 — Code Generator.

Walks the AST produced by ``parser.parse`` (already validated by
``semv.validate``) and emits a single, self-contained Python 3.12 script
that uses ``polars`` for every data-manipulation step and switches to
``pandas`` + ``matplotlib`` only when a ``PLOT`` statement is reached.

Design notes
------------
* The generator is a pure tree-walker: one ``_emit_*`` method per AST
  node kind, all writing into the same internal line buffer.
* ``FOR`` blocks are unrolled at compile time per spec section 6.3.
  Each iteration is materialised as a textual copy of the body in which
  the loop variable is replaced by the current column name.  The
  generated code therefore contains no Python-level ``for`` loop.
* ``IF`` blocks are lowered to a Python ``if/else`` whose guard is built
  from the ``MetaCondition`` tree (``EXISTS df.col``,
  ``ROWCOUNT df > N``, plus ``AND``/``OR``).
* ``READ '<path>'`` introduces a polars dataframe whose variable name is
  derived from the file stem with the same rule the validator uses
  (``_dataset_name_from_path``).  The most recently introduced
  dataframe is the *active* one and is referenced as ``df`` in the
  emitted code via an alias assignment.
* ``PLOT`` materialises ``df.to_pandas()`` once and then dispatches on
  the chart kind.

Public entry point
------------------
``generate(ast: list[ASTNode]) -> str``
"""
